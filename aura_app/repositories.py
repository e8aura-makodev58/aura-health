"""Replaceable persistence contracts for the application layer."""

from contextlib import AbstractContextManager
from typing import Any, Protocol


class RepositoryConflict(Exception):
    pass


class PatientRepository(Protocol):
    def patient(self, patient_id: str) -> dict[str, Any] | None: ...
    def create_patient(self, row: dict[str, Any]) -> None: ...
    def save_treatment(self, row: dict[str, Any]) -> None: ...
    def save_wearable_source(self, row: dict[str, Any]) -> None: ...


class EventRepository(Protocol):
    def prior_result(self, patient_id: str, idempotency_key: str) -> dict[str, Any] | None: ...
    def events(self, patient_id: str) -> list[dict[str, Any]]: ...
    def committed_results(self, patient_id: str) -> list[dict[str, Any]]: ...
    def save_event(self, row: dict[str, Any]) -> None: ...
    def save_result(self, event_id: str, result: dict[str, Any]) -> None: ...
    def timeline(self, patient_id: str) -> list[dict[str, Any]]: ...
    def append_timeline(self, row: dict[str, Any]) -> None: ...


class ObservationRepository(Protocol):
    def save_observation(self, row: dict[str, Any]) -> None: ...
    def observations(self, patient_id: str) -> list[dict[str, Any]]: ...
    def save_checkin(self, row: dict[str, Any]) -> None: ...
    def save_medication(self, row: dict[str, Any]) -> None: ...
    def medication_events(self, patient_id: str) -> list[dict[str, Any]]: ...


class BaselineRepository(Protocol):
    def save_baseline(self, row: dict[str, Any]) -> None: ...
    def baselines(self, patient_id: str) -> list[dict[str, Any]]: ...


class ContextRepository(Protocol):
    def save_context(self, row: dict[str, Any]) -> None: ...
    def save_explanation(self, row: dict[str, Any]) -> None: ...
    def update_explanation_status(self, event_id: str, status: str) -> None: ...
    def save_held(self, row: dict[str, Any]) -> None: ...
    def held(self, patient_id: str) -> list[dict[str, Any]]: ...


class ReviewRepository(Protocol):
    def save_review_item(self, row: dict[str, Any]) -> None: ...
    def review_items(self, patient_id: str) -> list[dict[str, Any]]: ...


class AuditRepository(Protocol):
    def append_audit(self, row: dict[str, Any]) -> None: ...
    def audit(self, patient_id: str) -> list[dict[str, Any]]: ...
    def append_safety_audit(self, row: dict[str, Any]) -> None: ...


class CommunicationRepository(Protocol):
    def communication_record(self, communication_id: str) -> dict[str, Any] | None: ...
    def append_communication_record(self, communication_id: str, row: dict[str, Any]) -> None: ...
    def communication_records(self, patient_id: str) -> list[dict[str, Any]]: ...


class AgentRepository(Protocol):
    def agent_run(self, patient_id: str, run_id: str) -> dict[str, Any] | None: ...
    def append_agent_run(self, row: dict[str, Any]) -> None: ...
    def workflow_run(self, patient_id: str, run_id: str) -> dict[str, Any] | None: ...
    def append_workflow_run(self, row: dict[str, Any]) -> None: ...
    def workflow_runs(self, patient_id: str) -> list[dict[str, Any]]: ...


class UnitOfWork(PatientRepository, EventRepository, ObservationRepository,
                 BaselineRepository, ContextRepository, ReviewRepository,
                 AuditRepository, CommunicationRepository, AgentRepository, Protocol):
    def safety_state(self, patient_id: str) -> dict[str, Any] | None: ...
    def save_safety_state(self, patient_id: str, state: dict[str, Any]) -> None: ...
    def save_safety_reference(self, row: dict[str, Any]) -> None: ...
    def safety_references(self, patient_id: str) -> list[dict[str, Any]]: ...
    def save_archived_safety_episode(self, row: dict[str, Any]) -> None: ...
    def consents(self, patient_id: str) -> list[dict[str, Any]]: ...
    def save_consent(self, row: dict[str, Any]) -> None: ...


class RepositoryFactory(Protocol):
    def transaction(self) -> AbstractContextManager[UnitOfWork]: ...
